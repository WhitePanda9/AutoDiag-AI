"""Evidence-aware follow-up questions for incomplete investigations.

Questions are generated by deterministic rules rather than by the LLM, so every
question has a fixed reason the application can show to the user. Rules cover
the common OBD-II fault families, safety-critical symptoms come first, and the
symptom checklist is built from the retrieved knowledge-base evidence, so the
user is only asked to confirm symptoms that are documented for their codes.
"""

import re
from dataclasses import dataclass
from typing import Any, Callable

MAX_QUESTIONS = 4
MAX_SYMPTOM_OPTIONS = 6
MAX_ANSWER_CHARS = 200
NOT_SURE = "Not sure"
NONE_OF_THESE = "None of these"
NOTES_ID = "additional_notes"
NOTES_QUESTION = "Anything else you noticed?"

SAFETY_TERMS = ("high voltage", "electric shock", "airbag", "brake", "fuel leak", "overheat")


@dataclass(frozen=True)
class Context:
    codes: tuple[str, ...]
    freeze_frame: dict
    evidence_text: str
    evidence_symptoms: tuple[str, ...]

    def has_code(self, *codes: str) -> bool:
        return any(code in self.codes for code in codes)

    def has_prefix(self, *prefixes: str) -> bool:
        return any(code.startswith(prefixes) for code in self.codes)

    def in_range(self, start: str, end: str) -> bool:
        """True if any code lies in an inclusive range of same-letter hex codes, e.g. P0420-P0439."""
        letter = start[0]
        low, high = int(start[1:], 16), int(end[1:], 16)
        return any(
            code[0] == letter and re.fullmatch(r"[0-9A-F]{4}", code[1:]) and low <= int(code[1:], 16) <= high
            for code in self.codes
        )

    def mentions(self, *terms: str) -> bool:
        return any(term in self.evidence_text for term in terms)


@dataclass(frozen=True)
class Rule:
    id: str
    question: str
    reason: str
    options: tuple[str, ...]
    applies: Callable[[Context], bool]
    multi: bool = False
    # Supplementary questions refine an interview but never start one on their own.
    supplementary: bool = False


RULES: tuple[Rule, ...] = (
    Rule(
        "safety_check",
        "Is the vehicle showing any of these right now?",
        "Safety-critical symptoms decide whether the vehicle should be driven at all.",
        ("Temperature gauge in the red or steam", "Brake or ABS warning light", "Airbag warning light",
         "Smell of fuel", NONE_OF_THESE),
        lambda c: c.mentions(*SAFETY_TERMS) or c.has_prefix("C", "B"),
        multi=True,
    ),
    Rule(
        "mil_state",
        "Is the check-engine light steady or flashing?",
        "A flashing light signals a severe misfire that can quickly damage the catalytic converter.",
        ("Steady", "Flashing", "Off now", NOT_SURE),
        lambda c: c.in_range("P0300", "P0312"),
    ),
    Rule(
        "operating_condition",
        "When does the fault occur?",
        "Operating conditions help distinguish intermittent, load-related and idle-related faults.",
        ("At idle", "While accelerating", "At cruising speed or under load", "Only on a cold start",
         "All the time", NOT_SURE),
        lambda c: not c.freeze_frame,
    ),
    Rule(
        "misfire_behavior",
        "Does the engine shake at idle, only when accelerating, or continuously?",
        "Misfire behaviour helps narrow ignition, fuel and air-intake causes.",
        ("Shakes at idle", "Only when accelerating", "Continuously", "No shaking", NOT_SURE),
        lambda c: c.in_range("P0300", "P0312"),
    ),
    Rule(
        "air_leak_signs",
        "Do you notice any signs of an air leak?",
        "These symptoms help assess a possible vacuum or unmetered-air leak.",
        ("Hissing sound from the engine bay", "Rough idle", "Reduced fuel economy",
         "Hesitation when accelerating", NONE_OF_THESE),
        lambda c: c.has_code("P0171", "P0174") or c.mentions("lean"),
        multi=True,
    ),
    Rule(
        "rich_signs",
        "Do you notice any signs of the engine running rich?",
        "These symptoms help separate a leaking injector or high fuel pressure from a sensor fault.",
        ("Black smoke from the exhaust", "Strong fuel smell", "Poor fuel economy", "Rough idle", NONE_OF_THESE),
        lambda c: c.has_code("P0172", "P0175") or c.mentions("rich condition", "running rich"),
        multi=True,
    ),
    Rule(
        "temperature_gauge",
        "What does the temperature gauge do while driving?",
        "Gauge behaviour separates a stuck thermostat, a cooling-system fault and a faulty sensor.",
        ("Stays normal", "Stays low or warms up slowly", "Rises into the red", "Fluctuates", NOT_SURE),
        lambda c: c.in_range("P0115", "P0119") or c.in_range("P0125", "P0128") or c.has_code("P0217")
        or c.mentions("overheat", "thermostat"),
    ),
    Rule(
        "catalyst_signs",
        "Do you notice any exhaust or catalytic-converter symptoms?",
        "These symptoms help separate a failing catalytic converter from an oxygen-sensor or exhaust fault.",
        ("Rotten-egg smell", "Rattling under the car", "Loss of power", "Exhaust leak noise", NONE_OF_THESE),
        lambda c: c.in_range("P0420", "P0439"),
        multi=True,
    ),
    Rule(
        "fuel_cap",
        "Was the fuel cap recently removed, left loose, or replaced?",
        "A loose or worn fuel cap is the most common cause of evaporative-emission (EVAP) codes.",
        ("Yes, recently refuelled or replaced", "No, the cap seems fine", NOT_SURE),
        lambda c: c.in_range("P0440", "P0457"),
    ),
    Rule(
        "shift_quality",
        "How do the gear changes feel?",
        "Shift behaviour helps separate a solenoid or sensor fault from low or degraded transmission fluid.",
        ("Normal", "Harsh or jerky", "Slipping or delayed", "Stuck in one gear", NOT_SURE),
        lambda c: c.in_range("P0700", "P0799"),
    ),
    Rule(
        "battery_history",
        "Has the battery recently been replaced, jump-started, or run flat?",
        "Low or interrupted voltage often sets communication and module codes without a failed part.",
        ("Yes", "No", NOT_SURE),
        lambda c: c.has_prefix("U") or c.in_range("P0560", "P0563") or c.in_range("P0600", "P0606"),
    ),
    Rule(
        "evidence_symptoms",
        "Which of these documented symptoms do you notice?",
        "These symptoms are listed in the knowledge base for your codes; confirming them strengthens or weakens each cause.",
        (),  # filled from the retrieved evidence
        lambda c: bool(c.evidence_symptoms),
        multi=True,
        supplementary=True,
    ),
    Rule(
        "recent_work",
        "Was any repair or part replacement done shortly before the fault appeared?",
        "Recent work often explains a new fault, for example a disturbed connector or vacuum hose.",
        ("Yes", "No", NOT_SURE),
        lambda _: True,
        supplementary=True,
    ),
)


def _context(state: dict[str, Any]) -> Context:
    docs = state.get("retrieved_docs", [])
    symptoms: list[str] = []
    for doc in docs:
        for symptom in doc.get("symptoms", []):
            if symptom and symptom not in symptoms:
                symptoms.append(symptom)
    return Context(
        codes=tuple(code.strip().upper() for code in state.get("dtc_codes", []) if code.strip()),
        freeze_frame=state.get("freeze_frame") or {},
        evidence_text=" ".join(doc.get("text", "") for doc in docs).lower(),
        evidence_symptoms=tuple(symptoms[:MAX_SYMPTOM_OPTIONS]),
    )


def _as_question(rule: Rule, context: Context) -> dict[str, Any]:
    options = rule.options or context.evidence_symptoms + (NONE_OF_THESE,)
    return {
        "id": rule.id,
        "question": rule.question,
        "reason": rule.reason,
        "options": list(options),
        "multi": rule.multi,
    }


def plan_questions(state: dict[str, Any]) -> list[dict[str, Any]]:
    """Return the prioritised follow-up questions for this investigation (possibly none)."""
    context = _context(state)
    primary = [rule for rule in RULES if not rule.supplementary and rule.applies(context)]
    if not primary:
        return []
    supplementary = [rule for rule in RULES if rule.supplementary and rule.applies(context)]
    return [_as_question(rule, context) for rule in (primary + supplementary)[:MAX_QUESTIONS]]


def _clean_answer(answer: Any) -> str:
    if isinstance(answer, (list, tuple)):
        answer = "; ".join(str(item) for item in answer if item)
    text = " ".join(str(answer or "").split())
    if text in ("", NOT_SURE):
        return ""
    return text[:MAX_ANSWER_CHARS]


class InterviewAgent:
    def run(self, state: dict[str, Any]) -> dict[str, Any]:
        answers = state.get("symptom_answers") or {}
        if state.get("interview_complete") or answers:
            questions = {item["id"]: item["question"] for item in plan_questions(state)}
            questions[NOTES_ID] = NOTES_QUESTION
            findings = []
            for question_id, raw in answers.items():
                answer = _clean_answer(raw)
                if answer:
                    findings.append({"question": questions.get(question_id, question_id.replace("_", " ")),
                                     "answer": answer})
            state["interview_findings"] = findings
            state["needs_follow_up"] = False
            state.setdefault("trace", []).append({
                "stage": "interview",
                "status": "complete",
                "detail": f"Used {len(findings)} follow-up answer(s); unanswered questions were skipped."
                if findings else "Follow-up questions were skipped; diagnosing from the evidence alone.",
            })
            return state

        questions = plan_questions(state)
        state["follow_up_questions"] = questions
        state["needs_follow_up"] = bool(questions)
        state.setdefault("trace", []).append({
            "stage": "interview",
            "status": "questions_requested" if questions else "not_needed",
            "detail": f"Requested {len(questions)} targeted follow-up question(s)."
            if questions else "Enough context was supplied; no follow-up questions needed.",
        })
        return state
